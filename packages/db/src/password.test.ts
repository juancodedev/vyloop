import { describe, expect, it } from 'vitest';

import {
  checkPasswordPolicy,
  hashPassword,
  PASSWORD_MIN_LENGTH,
  verifyPassword,
} from './password';

// ---------------------------------------------------------------------------
// Compatibility fixtures
//
// The two implementations this module replaced were byte-for-byte identical in
// everything that reaches the stored string: a 16-byte random salt hex-encoded,
// PBKDF2-HMAC-SHA-256 at 100_000 iterations over the *hex text* of that salt,
// 512 derived bits hex-encoded, joined with a colon. If any of those moves, the
// hashes below stop verifying and every credential in the database is dead on
// deploy. That is the only compatibility surface this refactor has, so it is
// pinned with values produced by the pre-existing code rather than by the code
// under test — a fixture generated by `hashPassword` here would pass no matter
// what the function did, which is the failure mode this suite exists to prevent.
// ---------------------------------------------------------------------------

/**
 * A stored `saltHex:hashHex` pair as the previous implementations produced it.
 * Salt is 16 bytes; the derived key is 512 bits, so 128 hex chars after the
 * colon. `legacyDerive` below reproduces that pairing, and the test asserts a
 * hash written by the old algorithm still authenticates through the new
 * `verifyPassword`.
 */
const LEGACY_SALT = '0123456789abcdef0123456789abcdef';
const LEGACY_PASSWORD = 'hunter2hunter2';

/** Recompute the legacy derivation inline, so the fixture is self-checking. */
async function legacyDerive(password: string, saltHex: string): Promise<string> {
  const encoder = new TextEncoder();
  const key = await crypto.subtle.importKey(
    'raw',
    encoder.encode(password),
    { name: 'PBKDF2' },
    false,
    ['deriveBits'],
  );
  const derived = await crypto.subtle.deriveBits(
    { name: 'PBKDF2', salt: encoder.encode(saltHex), iterations: 100_000, hash: 'SHA-256' },
    key,
    512,
  );
  return Array.from(new Uint8Array(derived))
    .map((b) => b.toString(16).padStart(2, '0'))
    .join('');
}

// ---------------------------------------------------------------------------
// hashPassword
// ---------------------------------------------------------------------------

describe('hashPassword', () => {
  it('stores a 16-byte salt and a 512-bit hash joined by a colon', async () => {
    const stored = await hashPassword('a-long-enough-password');

    const [salt, hash] = stored.split(':');
    expect(salt).toMatch(/^[0-9a-f]{32}$/);
    expect(hash).toMatch(/^[0-9a-f]{128}$/);
  });

  it('salts each hash, so the same password never stores twice the same', async () => {
    const [a, b] = await Promise.all([hashPassword('same-password-here'), hashPassword('same-password-here')]);

    expect(a).not.toBe(b);
    expect(await verifyPassword('same-password-here', a)).toBe(true);
    expect(await verifyPassword('same-password-here', b)).toBe(true);
  });
});

// ---------------------------------------------------------------------------
// verifyPassword
// ---------------------------------------------------------------------------

describe('verifyPassword', () => {
  it('accepts the correct password', async () => {
    const stored = await hashPassword('the-right-password');

    expect(await verifyPassword('the-right-password', stored)).toBe(true);
  });

  it('rejects a wrong password', async () => {
    const stored = await hashPassword('the-right-password');

    expect(await verifyPassword('the-wrong-password', stored)).toBe(false);
  });

  it('rejects an empty password against a real hash', async () => {
    const stored = await hashPassword('the-right-password');

    expect(await verifyPassword('', stored)).toBe(false);
  });

  // The compatibility case. A credential written by the code this module
  // replaced must still authenticate, or the extraction is a mass lockout.
  it('verifies a password hashed by the pre-extraction implementation', async () => {
    const stored = `${LEGACY_SALT}:${await legacyDerive(LEGACY_PASSWORD, LEGACY_SALT)}`;

    expect(await verifyPassword(LEGACY_PASSWORD, stored)).toBe(true);
    expect(await verifyPassword('not-the-password', stored)).toBe(false);
  });

  it('produces a hash that the pre-extraction derivation also accepts', async () => {
    // The other direction of the same guarantee: a hash written by signup has
    // to be readable by anything still running the old algorithm.
    const stored = await hashPassword(LEGACY_PASSWORD);
    const [salt] = stored.split(':');

    expect(await legacyDerive(LEGACY_PASSWORD, salt)).toBe(stored.split(':')[1]);
  });

  // `users.password_hash` is nullable and a user with no password must fail the
  // check, not the request. These are the shapes a NULL column produces.
  it.each([
    ['empty string', ''],
    ['missing separator', 'no-colon-here'],
    ['empty hash half', '0123456789abcdef0123456789abcdef:'],
    ['empty salt half', ':abcdef'],
    ['just a colon', ':'],
  ])('rejects a malformed stored value (%s) instead of throwing', async (_label, stored) => {
    expect(await verifyPassword('any-password', stored)).toBe(false);
  });
});

// ---------------------------------------------------------------------------
// checkPasswordPolicy
// ---------------------------------------------------------------------------

describe('checkPasswordPolicy', () => {
  it('rejects a password shorter than the documented minimum', () => {
    const result = checkPasswordPolicy('a'.repeat(PASSWORD_MIN_LENGTH - 1));

    expect(result.ok).toBe(false);
    expect(result.ok === false && result.message).toContain(String(PASSWORD_MIN_LENGTH));
  });

  it('rejects the seed password, which is one character short', () => {
    expect(checkPasswordPolicy('demo123').ok).toBe(false);
  });

  it.each([
    ['an empty password', ''],
    ['a single character', 'a'],
    ['all spaces', ' '.repeat(PASSWORD_MIN_LENGTH)],
    ['all tabs and newlines', '\t\n '.repeat(PASSWORD_MIN_LENGTH)],
  ])('rejects %s', (_label, candidate) => {
    expect(checkPasswordPolicy(candidate).ok).toBe(false);
  });

  // Scoped to entirely-whitespace. A passphrase that merely *ends* in a space
  // keeps it — trimming the credential would silently change what the user
  // typed, and a password manager re-supplying the untrimmed value would then
  // fail to log in.
  it('keeps leading and trailing whitespace on a real passphrase', () => {
    expect(checkPasswordPolicy('  correct horse  ').ok).toBe(true);
  });

  it('accepts a password at exactly the minimum', () => {
    expect(checkPasswordPolicy('a'.repeat(PASSWORD_MIN_LENGTH)).ok).toBe(true);
  });

  it('accepts a passphrase well past the minimum', () => {
    expect(checkPasswordPolicy('correct horse battery staple').ok).toBe(true);
  });

  // No composition rules, on purpose. See the note on PASSWORD_MIN_LENGTH: the
  // rules are trivially satisfied by one substitution and measurably lower the
  // entropy of the population that has to satisfy them. A policy that grew a
  // regex here would be a regression disguised as a hardening.
  it('does not impose character-class rules on an accepted password', () => {
    expect(checkPasswordPolicy('aaaaaaaaaaaa').ok).toBe(true);
  });

  it('does not impose character-class rules on a mixed one either', () => {
    expect(checkPasswordPolicy('CORRECThorse42').ok).toBe(true);
  });

  it('states the minimum in the rejection, so the caller can relay it verbatim', () => {
    const result = checkPasswordPolicy('short');

    expect(result.ok === false && result.message).toBe(
      `Password must be at least ${PASSWORD_MIN_LENGTH} characters long`,
    );
  });
});
